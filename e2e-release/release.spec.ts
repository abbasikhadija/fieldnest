import { test, expect } from '@playwright/test'

test('release demo persists through offline reload across browser engines', async ({ page, context, baseURL }) => {
  await page.goto('./')
  await page.getByRole('button', { name: 'Try Fieldnest' }).click()
  await page.getByRole('link', { name: /12 Willow Court/ }).click()
  await page.getByRole('group', { name: 'Walls and ceilings are in good condition' }).getByRole('radio', { name: 'Fail', exact: true }).check()
  await expect(page.getByRole('status').filter({ hasText: /^Saved on this device/ })).toBeVisible()
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  expect(await page.evaluate(async () => (await navigator.serviceWorker.ready).scope)).toBe(baseURL)
  await page.reload()
  await expect(page.getByRole('radio', { name: 'Fail', exact: true }).first()).toBeChecked()
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('radio', { name: 'Fail', exact: true }).first()).toBeChecked()
  await page.getByRole('button', { name: '5. Review', exact: true }).click()
  await page.getByLabel('Additional observations').fill('Fictional release-check observation')
  await expect(page.getByRole('status').filter({ hasText: /^Saved on this device/ })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '5. Review', exact: true }).click()
  await expect(page.getByLabel('Additional observations')).toHaveValue('Fictional release-check observation')
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await context.setOffline(false)
})

